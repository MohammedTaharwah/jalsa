def seed_database_if_empty(db: Session):
    """
    يقوم بتهيئة قاعدة البيانات الأولية إذا كانت فارغة:
    - يضيف الفئات الـ 6 الأساسية
    - يضيف الأسئلة المصنفة مع مستويات الصعوبة (200، 400، 600)
    """
    total_cats = db.query(Category).count()
    total_questions = db.query(Question).count()

    if total_cats > 0 and total_questions > 0:
        return

    logger.info("Database is empty or missing questions. Seeding initial categories and questions...")

    for cat_data in INITIAL_CATEGORIES_DATA:
        category = db.query(Category).filter(Category.name == cat_data["name"]).first()
        if not category:
            category = Category(
                name=cat_data["name"],
                description=cat_data["description"],
                image_url=cat_data["image_url"]
            )
            db.add(category)
            db.commit()
            db.refresh(category)

        # Check existing questions in this category
        existing_q_count = db.query(Question).filter(Question.category_id == category.id).count()
        if existing_q_count < len(cat_data["questions"]):
            for q in cat_data["questions"]:
                exists = db.query(Question).filter(
                    Question.category_id == category.id,
                    Question.question_text == q["text"]
                ).first()
                if not exists:
                    new_q = Question(
                        category_id=category.id,
                        question_text=q["text"],
                        options_json=q["options"],
                        correct_answer=q["answer"],
                        points_level=q["points"],
                        status="active"
                    )
                    db.add(new_q)
            db.commit()

    logger.info(f"Database successfully seeded! Categories: {db.query(Category).count()}, Questions: {db.query(Question).count()}")
